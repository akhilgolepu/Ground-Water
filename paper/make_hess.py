"""
Builds the HESS submission version of the manuscript from paper/main.tex, so there is one source.

  python paper/make_hess.py        → paper/hess/main_hess.tex (+ PDF if latexmk is available)

The Copernicus LaTeX package (copernicus.cls, .cfg, .bst) is downloaded into paper/hess/ on first use and
is not committed (it carries its own copyright). The body text, tables and figures are taken unchanged
from main.tex; only the front matter and the end sections are mapped to the class's commands.
"""

import io
import re
import shutil
import subprocess
import sys
import urllib.request
import zipfile
from pathlib import Path

PAPER = Path(__file__).resolve().parent
OUT = PAPER / "hess"
PACKAGE_URL = "https://publications.copernicus.org/Copernicus_LaTeX_Package.zip"
CLASS_FILES = ("copernicus.cls", "copernicus.cfg", "copernicus.bst", "pdfscreen.sty", "pdfscreencop.sty")

# Front matter: author name and affiliation are the author's to complete.
AUTHOR = r"\Author[1][akhilgolepu9@gmail.com]{Akhil}{Golepu}"
AFFIL = r"\affil[1]{Affiliation to be completed by the author}"
RUNNING_TITLE = "Groundwater forecasting for India: forcing, calibration and decision value"
RUNNING_AUTHOR = "Golepu"


def ensure_class():
    OUT.mkdir(exist_ok=True)
    if all((OUT / f).exists() for f in CLASS_FILES):
        return
    with urllib.request.urlopen(urllib.request.Request(PACKAGE_URL, headers={"User-Agent": "aquasense"}), timeout=120) as r:
        z = zipfile.ZipFile(io.BytesIO(r.read()))
    for name in z.namelist():
        if Path(name).name in CLASS_FILES:
            (OUT / Path(name).name).write_bytes(z.read(name))


def section(src: str, start: str, end: str) -> str:
    i = src.index(start) + len(start)
    return src[i:src.index(end, i)].strip()


def build() -> Path:
    src = (PAPER / "main.tex").read_text()
    title = re.search(r"\\title\{(.+?)\}\n", src).group(1)
    abstract = section(src, r"\begin{abstract}", r"\end{abstract}")
    body = section(src, r"\section{Introduction}", r"\section*{Code and data availability}")
    body = body.replace(r"\section{Conclusions}", r"\conclusions", 1)
    availability = section(src, r"\section*{Code and data availability}", r"\section*{Author contributions")
    for old, new in ((r"\includegraphics[width=\textwidth]", r"\includegraphics[width=12cm]"),
                     (r"\includegraphics[width=0.85\textwidth]", r"\includegraphics[width=12cm]"),
                     (r"\includegraphics[width=0.75\textwidth]", r"\includegraphics[width=8.3cm]")):
        body = body.replace(old, new)
    body = body.replace(r"\input{tables/", r"\input{../tables/")

    tex = rf"""%% HESS submission version — GENERATED by paper/make_hess.py from paper/main.tex. Edit main.tex, not this file.
\documentclass[hess, manuscript]{{copernicus}}
\usepackage{{booktabs}}
\usepackage{{adjustbox}}
\graphicspath{{{{../figures/}}}}
\input{{../numbers.tex}}

\begin{{document}}

\title{{{title}}}

{AUTHOR}
{AFFIL}

\correspondence{{Akhil Golepu (akhilgolepu9@gmail.com)}}

\runningtitle{{{RUNNING_TITLE}}}
\runningauthor{{{RUNNING_AUTHOR}}}

\received{{}}
\pubdiscuss{{}}
\revised{{}}
\accepted{{}}
\published{{}}

\firstpage{{1}}

\maketitle

\begin{{abstract}}
{abstract}
\end{{abstract}}

\introduction
{body.split(chr(10), 1)[1]}

\codedataavailability{{{availability}}}

\authorcontribution{{To be completed by the author.}}

\competinginterests{{The author declares that there are no competing interests.}}

\bibliographystyle{{copernicus}}
\bibliography{{../../docs/references}}

\end{{document}}
"""
    path = OUT / "main_hess.tex"
    path.write_text(tex)
    return path


if __name__ == "__main__":
    ensure_class()
    path = build()
    print(f"Wrote {path}")
    if shutil.which("latexmk") and "--no-pdf" not in sys.argv:
        r = subprocess.run(["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", path.name],
                           cwd=OUT, capture_output=True, text=True)
        print("PDF built" if r.returncode == 0 else r.stdout[-3000:])
